// The token radar's model, radar-2: a comparables-calibrated valuation.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol
// is pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol);
// protocols whose token already trades are kept apart as the live set and shown with the market's
// own values, never mixed into the ranked board. Wrapped, staked and bridged products of a token
// that already trades are left out of the board entirely: they are not protocols still waiting on
// a launch of their own.
//
// Implied value is priced off the snapshot's own traded protocols, the way a market prices a
// listing off its peers, and follows only from the snapshot's figures:
//
//   comparables  For each category, the median market-cap / TVL of the traded protocols in that
//                category, from this snapshot alone. A category earns its own multiple only when
//                at least 4 traded protocols carry one; otherwise it takes the market median.
//                Ratios are clipped to [0.01, 1.5] before the median, so one outlier cannot set
//                a category, and every multiple is clamped to [0.08, 0.90].
//   base         = tvl_usd x category_multiple
//   growth       = clamp(change_7d, -50, 100) per cent
//   growthMult   = 1 + (growth / 100) x 0.6
//   maturity     = 0.75 + min(age_days, 1095) / 1095 x 0.35   (age_days unknown: 365)
//                Age is the time since DefiLlama first listed the protocol: how long it has run
//                with no token. Older, larger and still unlaunched is a longer record, not a
//                prediction that a token comes.
//   breadth      = 1 + 0.03 x min(chains - 1, 5)   (one chain: 1.00, six or more: 1.15)
//   implied      = max(1, round(base x growthMult x maturity x breadth))
//
// No protocol name is ever special-cased: the same function scores every row, and the multiples
// are recomputed from the snapshot on every run, so the model cannot be a hardcoded list.

